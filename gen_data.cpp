int main() {
    FILE* f = fopen("data.json", "w");
    if (!f) { fprintf(stderr, "Error: cannot write data.json\n"); return 1; }

    fprintf(f, "{\"inputs\":[\n");
    for (int i = 0; i < 26; i++) {
        fprintf(f, "  [");
        int first = 1;
        for (int r = 0; r < 7; r++) {
            for (int c = 0; c < 5; c++) {
                if (!first) fprintf(f, ",");
                fprintf(f, "%d", FONTS[i][r][c]);
                first = 0;
            }
        }
        fprintf(f, "]");
        if (i < 25) fprintf(f, ",");
        fprintf(f, "\n");
    }
    fprintf(f, "],\"targets\":[\n");
    for (int i = 0; i < 26; i++) {
        fprintf(f, "  [");
        for (int j = 0; j < 26; j++) {
            if (j > 0) fprintf(f, ",");
            fprintf(f, "%d", i == j ? 1 : 0);
        }
        fprintf(f, "]");
        if (i < 25) fprintf(f, ",");
        fprintf(f, "\n");
    }
    fprintf(f, "]}\n");
    fclose(f);
    printf("Wrote data.json (26 letters, 35 inputs each, 26-class one-hot targets)\n");
    return 0;
}
